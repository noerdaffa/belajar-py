#tipe data boolean
print (True)

#tipe data string
print("ayo belajar pyhton")
print('Belajar pyhton sangat mudah')

#tipe data integer
print(20)

#tipe data float
print(3.14)

#tipe data biner
print(bin(20))

#tipe data octal
print(oct(21))

#tipe data hexadesimal
print(hex(43))

#tipe data complex
print(1+5j)

#tipe data list
print([1,2,3,4,5])
print(["Satu", "Dua", "Tiga"])

#tipe data tuple 
print((1,2,3,4,5))
print(("Satu", "Dua", "Tiga"))

#tipe data Dictionary
print({"nama": "budi", 'umur':20})

#tipe data dictionary dimasukkan ke dalam variabel biodata
biodata = {"nama": "andi", 'umur': 21} #proses inisialisasi variabel biodata
print(biodata) #proses pencetakan variabel biodata yang berisi tipe data
print(type(biodata)) #fungsi untuk mengecek jenis tipe data. akan tampil <class 'dict'> yang berarti adalah tipe data dictionary
