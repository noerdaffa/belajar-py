#SAMA DENGAN
print(1 == 1) #hasilnya akan bernilai true karna satu sama dengan satu
print(1 == 2) #hasilnya akan bernilai false karna satu tidak sama dengan satu

#TIDAK SAMA DENGAN
print(2 != 2) #hasilnya akan bernilai false karna dua seharusnyaa
print(2 != 3) #hasilnya akan bernilai true karna dua tidak sama

#LEBIH BESAR DARI
print(5 > 3) #hasilnya akan bernilai true karna lima lebih besar

#LEBIH KECIL DARI
print(5 < 3) #hasilnya akan bernilai false karna lima lebih besar dari tiga

#LEBIH BESAR DARI SAMA DENGAN
print(5 >= 3) #hasilnya akan bernilai true karna lima lebih besar

#LEBIH KECIL DARI SAMA DENGAN 
print(5 <= 3) #hasilnya akan bernilai false karna lima tidak lebih besar

 
